/** Arabic letters written several ways are made one, so a search does not depend on how the word was typed. */
export const normalizeForSearch = (text: string) =>
  text
    .toLowerCase()
    .replace(/[\u064B-\u0652\u0640]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .trim();

/** The first icon whose keyword appears in the name, or null. Only a starting point: staff can change it. */
export function suggestServiceIcon(name: string): ServiceIcon | null {
  const text = normalizeForSearch(name);
  for (const [icon, words] of KEYWORDS) {
    if (words.some((word) => text.includes(normalizeForSearch(word)))) return icon;
  }
  return null;
}
